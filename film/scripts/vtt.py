#!/usr/bin/env python3
"""
Write the film's caption track from the voiceover script.

    python3 scripts/vtt.py      # → ../web/public/demo/slate-film.en.vtt

The voice reads the on-screen captions word-for-word, so the VO script *is* the
transcript — there is nothing to transcribe and nothing that can drift. Cue ends
are the mp3 duration plus 150ms, so a caption never blinks out on the last
syllable.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
cfg = json.loads((ROOT / "scripts/vo-script.json").read_text())


def dur(i: str) -> float:
    return float(
        subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
             str(ROOT / f"public/vo/{i}.mp3")],
            capture_output=True,
        ).stdout.strip()
    )


def ts(sec: float) -> str:
    h, rem = divmod(sec, 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"


out = ["WEBVTT", "", "NOTE Generated by scripts/vtt.py from scripts/vo-script.json.", ""]
for i, line in enumerate(cfg["lines"], 1):
    a = line["f"] / 30
    out += [str(i), f"{ts(a)} --> {ts(a + dur(line['id']) + 0.15)}", line["text"], ""]

dest = ROOT.parent / "web/public/demo/slate-film.en.vtt"
dest.write_text("\n".join(out))
print(f"{dest.relative_to(ROOT.parent)} · {len(cfg['lines'])} cues")
